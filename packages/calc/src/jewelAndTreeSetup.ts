// 3. Jewel Effect Scaling (`The Adorned` + Prefix/Suffix Effect + Numeric Scaler)
// ---------------------------------------------------------------------------

/**
 * Scales numeric rolls in a single stat line by `mult` using PoB integer truncation:
 * - Integer values (e.g. `+14`, `20%`) -> `Math.trunc(val * mult)`
 * - Decimal values (e.g. `+1.5%`, `0.4%`) -> truncated to the original number of decimal places
 *
 * Preserves leading `+`/`-` signs and surrounding text.
 */
export function scaleStatLineNumeric(line: string, mult: number): string {
  if (mult === 1 || !Number.isFinite(mult)) return line;
  return line.replace(
    /([+-]?)(\d+(?:\.\d+)?)/g,
    (_full, sign: string, numStr: string) => {
      const val = Number(numStr);
      const dotIdx = numStr.indexOf('.');
      if (dotIdx === -1) {
        const scaled = Math.trunc(val * mult);
        return `${sign}${scaled}`;
      }
      const decimals = numStr.length - dotIdx - 1;
      const factor = Math.pow(10, decimals);
      const scaled = Math.trunc(val * mult * factor) / factor;
      return `${sign}${scaled}`;
    },
  );
}

/**
 * Computes the delta stat line representing the extra effect `(mult - 1)` with exact PoB truncation:
 * `Math.trunc(val * mult) - val` for integers (and decimal-truncated delta for floats).
 * Returns `null` if every numeric value has zero delta.
 */
function scaleStatLineDelta(line: string, mult: number): string | null {
  if (mult === 1 || !Number.isFinite(mult)) return null;
  // PoB 2 ScaleAddList preserves 2-decimal precision for small flat base crit bonuses
  // (e.g. Struck Through "Attacks have +1% to Critical Hit Chance" * 1.22 -> +0.22% delta).
  const isBaseCritLine = /\+\d+(?:\.\d+)?%\s+to\s+Critical\s+(?:Hit|Strike)\s+Chance/i.test(line);
  let anyNonZero = false;
  const out = line.replace(
    /([+-]?)(\d+(?:\.\d+)?)/g,
    (_full, sign: string, numStr: string) => {
      const val = Number(numStr);
      const dotIdx = numStr.indexOf('.');
      if (dotIdx === -1 && !isBaseCritLine) {
        const delta = Math.trunc(val * mult) - val;
        if (delta !== 0) anyNonZero = true;
        return `${sign}${delta}`;
      }
      const decimals = dotIdx === -1 ? 2 : numStr.length - dotIdx - 1;
      const factor = Math.pow(10, decimals);
      const scaled = Math.trunc(val * mult * factor + 1e-9) / factor;
      const delta = Math.round((scaled - val) * factor) / factor;
      if (delta !== 0) anyNonZero = true;
      return `${sign}${delta}`;
    },
  );
  return anyNonZero ? out : null;
}

function joinWrappedJewelLines(rawLines: readonly string[]): string[] {
  const out: string[] = [];
  for (const raw of rawLines) {
    const clean = stripPobTags(raw);
    if (!clean) continue;
    if (out.length > 0 && /^[a-z]/.test(clean)) {
      out[out.length - 1] = `${out[out.length - 1]} ${clean}`;
    } else {
      out.push(clean);
    }
  }
  return out;
}

/**
 * Computes `The Adorned` global scaling and PoE 2 Prefix/Suffix effect scaling for a jewel.
 */
export function computeJewelEffectScale(
  jewel: Item,
  allJewels: readonly Item[],
  game: GameId,
): JewelEffectScale {
  let prefixPct = 0;
  let suffixPct = 0;

  // 1. Local Prefix/Suffix effect modifiers on this jewel.
  // In PoE 2 (`Classes/Item.lua:1649`), non-crafted in-game item copies (`rawText` present without
  // `Crafted: true`, `Prefix:`/`Prefixes:`, or `{tags:...}`) already have Prefix/Suffix magnitude baked into explicit numbers.
  const applyLocalAffixMagnitude =
    game !== 'poe2' ||
    !jewel.rawText ||
    /^\s*(?:Crafted\s*:\s*true|Prefix(?:es)?\s*:)/im.test(jewel.rawText) ||
    /\{tags:/i.test(jewel.rawText);

  const ownLines = joinWrappedJewelLines([...jewel.implicits, ...jewel.explicits]);
  if (applyLocalAffixMagnitude) {
    for (const line of ownLines) {
      let m = line.match(/^(\d+)% increased Effect of Prefixes$/i);
      if (m) {
        prefixPct += Number(m[1]);
        continue;
      }
      m = line.match(/^(\d+)% reduced Effect of Prefixes$/i);
      if (m) {
        prefixPct -= Number(m[1]);
        continue;
      }
      m = line.match(/^(\d+)% increased Effect of Suffixes$/i);
      if (m) {
        suffixPct += Number(m[1]);
        continue;
      }
      m = line.match(/^(\d+)% reduced Effect of Suffixes$/i);
      if (m) {
        suffixPct -= Number(m[1]);
        continue;
      }
    }
  }

  // 2. Global "The Adorned" scaling across all active jewels
  let adornedMagicPct = 0;
  let adornedRarePct = 0;

  for (const other of allJewels) {
    const lines = joinWrappedJewelLines([...other.implicits, ...other.explicits]);
    for (const line of lines) {
      const m = line.match(
        /^(\d+)% increased Effect of (?:Jewel Socket Passive Skills containing|Socketed) Corrupted (Magic|Rare|Magic or Rare) Jewels$/i,
      );
      if (!m) continue;
      const pct = Number(m[1]);
      const target = m[2]!.toLowerCase();
      if (target === 'magic' || target === 'magic or rare') {
        adornedMagicPct = Math.max(adornedMagicPct, pct);
      }
      if (target === 'rare' || target === 'magic or rare') {
        adornedRarePct = Math.max(adornedRarePct, pct);
      }
    }
  }

  let globalScale = 1;
  const isPoe2Sinister = game === 'poe2' && poe2SinisterSocketJewels.has(jewel);
  if (!isPoe2Sinister && isItemCorrupted(jewel)) {
    if (jewel.rarity === 'MAGIC' && adornedMagicPct > 0) {
      globalScale = 1 + adornedMagicPct / 100;
    } else if (jewel.rarity === 'RARE' && adornedRarePct > 0) {
      globalScale = 1 + adornedRarePct / 100;
    }
  }

  return {
    prefixScale: Math.max(0, 1 + prefixPct / 100),
    suffixScale: Math.max(0, 1 + suffixPct / 100),
    globalScale,
  };
}

/**
 * Counts how many non-"None" prefix lines are declared in PoB XML `rawText` (`Prefixes:` ... `Suffixes:`).
 * Returns `null` if `rawText` has no explicit `Prefixes:` section.
 */
function parseRawPrefixCount(rawText?: string): number | null {
  if (!rawText) return null;
  const lines = rawText.split(/\r?\n/);
  let inPrefixes = false;
  let count = 0;
  let foundHeader = false;
  for (const raw of lines) {
    const trimmed = raw.trim();
    if (/^Prefixes\s*:/i.test(trimmed)) {
      inPrefixes = true;
      foundHeader = true;
      continue;
    }
    if (inPrefixes) {
      if (
        /^Suffixes\s*:/i.test(trimmed) ||
        /^Quality\s*:/i.test(trimmed) ||
        /^Implicits\s*:/i.test(trimmed) ||
        /^LevelReq\s*:/i.test(trimmed) ||
        trimmed === ''
      ) {
        break;
      }
      const cleaned = trimmed.replace(/\{[^}]+\}/g, '').trim();
      if (cleaned && cleaned.toLowerCase() !== 'none') {
        count++;
      }
    }
  }
  return foundHeader ? count : null;
}

function isPrefixSuffixEffectMetaLine(line: string): boolean {
  return /^\d+% (?:increased|reduced) Effect of (?:Prefixes|Suffixes)$/i.test(
    stripPobTags(line),
  );
}

/** Tracks line arrays already produced by `scaleJewelModLines` so `evaluateRadiusAndDistanceJewels` never double-scales. */
const preScaledJewelLineArrays = new WeakSet<readonly string[]>();

/**
 * Applies `computeJewelEffectScale` (The Adorned + Prefix/Suffix effect) to all implicits & explicits
 * of a jewel, returning scaled stat lines ready for `parseModLines`.
 */
export function scaleJewelModLines(
  jewel: Item,
  allJewels: readonly Item[],
  game: GameId,
  socketEffectPct = 0,
): { implicits: string[]; explicits: string[]; scale: JewelEffectScale } {
  const baseScale = computeJewelEffectScale(jewel, allJewels, game);
  const scale: JewelEffectScale =
    socketEffectPct !== 0
      ? {
          ...baseScale,
          globalScale: Math.max(0, baseScale.globalScale * (1 + socketEffectPct / 100)),
        }
      : baseScale;
  const { prefixScale, suffixScale, globalScale } = scale;

  const implicits = jewel.implicits.map((line) => {
    if (globalScale === 1 || isPrefixSuffixEffectMetaLine(line)) return line;
    return scaleStatLineNumeric(line, globalScale);
  });

  if (prefixScale === 1 && suffixScale === 1 && globalScale === 1) {
    const explicits = [...jewel.explicits];
    preScaledJewelLineArrays.add(implicits);
    preScaledJewelLineArrays.add(explicits);
    return { implicits, explicits, scale };
  }

  // Determine prefix/suffix split index among non-meta explicit lines
  const nonMetaIndices: number[] = [];
  for (let i = 0; i < jewel.explicits.length; i++) {
    if (!isPrefixSuffixEffectMetaLine(jewel.explicits[i]!)) {
      nonMetaIndices.push(i);
    }
  }

  const rawPrefixCount = parseRawPrefixCount(jewel.rawText);
  const prefixCount =
    rawPrefixCount !== null
      ? Math.min(rawPrefixCount, nonMetaIndices.length)
      : Math.floor(nonMetaIndices.length / 2);

  const prefixSet = new Set<number>(nonMetaIndices.slice(0, prefixCount));

  const explicits = jewel.explicits.map((line, idx) => {
    if (isPrefixSuffixEffectMetaLine(line)) return line;
    const affixMult = prefixSet.has(idx) ? prefixScale : suffixScale;
    const totalMult = globalScale * affixMult;
    return totalMult === 1 ? line : scaleStatLineNumeric(line, totalMult);
  });

  preScaledJewelLineArrays.add(implicits);
  preScaledJewelLineArrays.add(explicits);
  return { implicits, explicits, scale };
}

