/**
 * Computes BFS shortest-path node count strictly between `socketNodeId` and `classStartNodeId`
 * traversing only allocated passive nodes (matching official PoB1 `SetNodeDistanceToClassStart`).
 *
 * Example: `ClassStart -- N1 -- N2 -- N3 -- Socket` returns `3`.
 * Returns `0` if unreachable or if `socketNodeId === classStartNodeId`.
 */
export function computeSplitPersonalityDistance(
  tree: PassiveTreeData,
  activeTreeNodes: Set<number>,
  classStartNodeId: number,
  socketNodeId: number,
): number {
  if (socketNodeId === classStartNodeId) return 0;
  const startNode = tree.nodes[socketNodeId];
  if (!startNode) return 0;

  const dist = new Map<number, number>();
  dist.set(socketNodeId, 0);
  const queue: number[] = [socketNodeId];
  let head = 0;

  while (head < queue.length) {
    const curId = queue[head++]!;
    const curNode = tree.nodes[curId];
    if (!curNode) continue;
    const nextDist = (dist.get(curId) ?? 0) + 1;

    for (const adjId of curNode.adjacent) {
      if (adjId === classStartNodeId) {
        return Math.max(0, nextDist - 1);
      }
      if (dist.has(adjId)) continue;
      if (!activeTreeNodes.has(adjId)) continue;
      const adjNode = tree.nodes[adjId];
      if (!adjNode) continue;
      if (adjNode.kind === 'mastery' || adjNode.kind === 'start') continue;

      dist.set(adjId, nextDist);
      queue.push(adjId);
    }
  }

  return 0;
}

function getAllocatedNodesInRadius(
  socketNode: PassiveNode,
  tree: PassiveTreeData,
  activeTreeNodes: Set<number>,
  radiusPx: number,
): PassiveNode[] {
  const rSq = radiusPx * radiusPx;
  const out: PassiveNode[] = [];

  for (const id of activeTreeNodes) {
    if (id === socketNode.id) continue;
    const node = tree.nodes[id];
    if (!node) continue;
    if (node.kind === 'mastery' || node.kind === 'start') continue;
    const dx = node.x - socketNode.x;
    const dy = node.y - socketNode.y;
    if (dx * dx + dy * dy <= rSq) {
      out.push(node);
    }
  }

  return out;
}

const ATTR_NAME_TO_MOD: Record<string, 'Str' | 'Dex' | 'Int'> = {
  strength: 'Str',
  dexterity: 'Dex',
  intelligence: 'Int',
};

/**
 * Evaluates all radius-based and distance-based jewels:
 * - PoE 2 `Time-Lost` Jewels & `Against the Darkness`
 *   - `Notable Passive Skills in Radius also grant <ModLine>`
 *   - `Small Passive Skills in Radius also grant <ModLine>`
 *   - `X% increased Effect of Notable/Small Passive Skills in Radius`
 * - PoE 1 `The Light of Meaning` (`Passive Skills in Radius also grant <ModLine>`)
 * - PoE 1 `Might of the Meek` (`50% increased Effect of non-Keystone Passive Skills in Radius` + suppresses Notables in radius)
 * - PoE 1 `Split Personality` (BFS distance `D` from `classStartNodeId`, scaling explicit stats by `1 + 0.25 * D` via delta)
 * - PoE 1 Attribute Conversion Jewels (`Fluid Motion`, `Brute Force Solution`, `Careful Planning`, `Fertile Mind`, `Inertia`)
 */
export function evaluateRadiusAndDistanceJewels(
  jewels: ReadonlyArray<{ nodeId: number; jewel: Item }>,
  tree: PassiveTreeData,
  activeTreeNodes: Set<number>,
  classStartNodeId: number,
): RadiusAndDistanceJewelResult {
  const addedStatLines: Array<{ source: string; lines: string[] }> = [];
  const addedMods: Mod[] = [];
  const suppressedNodeIds = new Set<number>();
  const details: RadiusAndDistanceJewelDetail[] = [];

  for (const { nodeId, jewel } of jewels) {
    const socketNode = tree.nodes[nodeId];
    const allLines = [...jewel.implicits, ...jewel.explicits].map(stripPobTags);
    const lowerName = jewel.name.toLowerCase();

    // --- A. Split Personality (BFS shortest-path distance scaling) ---
    let splitPctPerNode = 0;
    for (const line of allLines) {
      const m = line.match(
        /This Jewel's Socket has (\d+)% increased effect per Allocated Passive Skill between/i,
      );
      if (m) {
        splitPctPerNode = Number(m[1]);
        break;
      }
    }
    if (splitPctPerNode === 0 && lowerName === 'split personality') {
      splitPctPerNode = 25;
    }

    if (splitPctPerNode > 0 && socketNode) {
      const dist = computeSplitPersonalityDistance(
        tree,
        activeTreeNodes,
        classStartNodeId,
        nodeId,
      );
      if (dist > 0) {
        const mult = 1 + (splitPctPerNode / 100) * dist;
        const deltaLines: string[] = [];
        for (const rawExp of jewel.explicits) {
          const clean = stripPobTags(rawExp);
          if (
            !clean ||
            /This Jewel's Socket has/i.test(clean) ||
            /it and your Class' starting location/i.test(clean) ||
            /^Limited to:/i.test(clean) ||
            /^Corrupted$/i.test(clean)
          ) {
            continue;
          }
          const delta = scaleStatLineDelta(clean, mult);
          if (delta) deltaLines.push(delta);
        }
        if (deltaLines.length > 0) {
          addedStatLines.push({
            source: `Split Personality (${nodeId}, dist=${dist})`,
            lines: deltaLines,
          });
        }
      }
      details.push({
        nodeId,
        jewelName: jewel.name,
        kind: 'split-personality',
        bfsDistance: dist,
      });
      continue;
    }

    // All remaining jewel types require a socket node with coordinates in `tree.nodes`
    if (!socketNode) continue;

    // Detect whether this jewel has any radius mechanics
    const notableAlsoGrants: string[] = [];
    const smallAlsoGrants: string[] = [];
    const allAlsoGrants: string[] = [];
    let notableEffectPct = 0;
    let smallEffectPct = 0;
    let nonKeystoneEffectPct = 0;
    let disablesNotables = false;
    let disablesAllocatedSmalls = false;
    let grantsUnallocatedSmalls = false;
    let eternalHubrisConquered = false;
    const attrConversions: Array<{ from: 'Str' | 'Dex' | 'Int'; to: 'Str' | 'Dex' | 'Int' }> = [];

    for (const line of allLines) {
      let m = line.match(/^Notable Passive Skills in Radius also grant\s+(.+)$/i);
      if (m) {
        notableAlsoGrants.push(m[1]!.trim());
        continue;
      }
      m = line.match(/^Small Passive Skills in Radius also grant\s+(.+)$/i);
      if (m) {
        smallAlsoGrants.push(m[1]!.trim());
        continue;
      }
      m = line.match(/^Passive Skills in Radius also grant\s+(.+)$/i);
      if (m) {
        allAlsoGrants.push(m[1]!.trim());
        continue;
      }
      m = line.match(
        /^(\d+)% increased Effect of Notable Passive Skills in Radius$/i,
      );
      if (m) {
        notableEffectPct += Number(m[1]);
        continue;
      }
      m = line.match(
        /^(\d+)% increased Effect of Small Passive Skills in Radius$/i,
      );
      if (m) {
        smallEffectPct += Number(m[1]);
        continue;
      }
      m = line.match(
        /^(\d+)% increased Effect of non-Keystone Passive Skills in Radius$/i,
      );
      if (m) {
        nonKeystoneEffectPct += Number(m[1]);
        continue;
      }
      if (/^Notable Passive Skills in Radius grant nothing$/i.test(line)) {
        disablesNotables = true;
        continue;
      }
      if (/^Allocated Small Passive Skills in Radius grant nothing$/i.test(line)) {
        disablesAllocatedSmalls = true;
        continue;
      }
      if (/^Grants all bonuses of Unallocated Small Passive Skills in Radius$/i.test(line)) {
        grantsUnallocatedSmalls = true;
        continue;
      }
      if (/^Passives in radius are Conquered by the Eternal Empire$/i.test(line)) {
        eternalHubrisConquered = true;
        continue;
      }
      m = line.match(
        /^(Strength|Dexterity|Intelligence) from Passives in Radius is Transformed to (Strength|Dexterity|Intelligence)$/i,
      );
      if (m) {
        const from = ATTR_NAME_TO_MOD[m[1]!.toLowerCase()];
        const to = ATTR_NAME_TO_MOD[m[2]!.toLowerCase()];
        if (from && to && from !== to) {
          attrConversions.push({ from, to });
        }
        continue;
      }
    }

    const hasRadiusEffect =
      notableAlsoGrants.length > 0 ||
      smallAlsoGrants.length > 0 ||
      allAlsoGrants.length > 0 ||
      notableEffectPct > 0 ||
      smallEffectPct > 0 ||
      nonKeystoneEffectPct > 0 ||
      disablesNotables ||
      disablesAllocatedSmalls ||
      grantsUnallocatedSmalls ||
      eternalHubrisConquered ||
      attrConversions.length > 0;

    if (!hasRadiusEffect) continue;

    const radiusLabel = resolveJewelRadiusLabel(jewel, tree.game);
    const radiusPx = getJewelRadiusPx(radiusLabel, tree.game, tree.version);
    const inRadius = getAllocatedNodesInRadius(
      socketNode,
      tree,
      activeTreeNodes,
      radiusPx,
    );

    const notables = inRadius.filter((n) => n.kind === 'notable');
    const smalls = inRadius.filter((n) => n.kind === 'small');
    const nonJewelPassives = inRadius.filter((n) => n.kind !== 'jewel');

    // --- B. PoE 2 Time-Lost & Against the Darkness ---
    if (
      notableAlsoGrants.length > 0 ||
      smallAlsoGrants.length > 0 ||
      notableEffectPct > 0 ||
      smallEffectPct > 0
    ) {
      const lines: string[] = [];

      for (const grantLine of notableAlsoGrants) {
        for (let i = 0; i < notables.length; i++) {
          lines.push(grantLine);
        }
      }
      for (const grantLine of smallAlsoGrants) {
        for (let i = 0; i < smalls.length; i++) {
          lines.push(grantLine);
        }
      }

      if (notableEffectPct > 0) {
        const mult = 1 + notableEffectPct / 100;
        for (const n of notables) {
          for (const st of n.stats) {
            const delta = scaleStatLineDelta(st, mult);
            if (delta) lines.push(delta);
          }
        }
      }

      if (smallEffectPct > 0) {
        const mult = 1 + smallEffectPct / 100;
        for (const n of smalls) {
          for (const st of n.stats) {
            const delta = scaleStatLineDelta(st, mult);
            if (delta) lines.push(delta);
          }
        }
      }

      if (lines.length > 0) {
        addedStatLines.push({
          source: `Radius Jewel (${nodeId}): ${jewel.name}`,
          lines,
        });
      }

      details.push({
        nodeId,
        jewelName: jewel.name,
        kind: 'time-lost',
        radiusLabel,
        radiusPx,
        nodesInRadius: inRadius.length,
        notablesInRadius: notables.length,
        smallsInRadius: smalls.length,
      });
    }

    // --- C. PoE 1 The Light of Meaning ---
    if (allAlsoGrants.length > 0) {
      const lines: string[] = [];
      for (const grantLine of allAlsoGrants) {
        for (let i = 0; i < nonJewelPassives.length; i++) {
          lines.push(grantLine);
        }
      }
      if (lines.length > 0) {
        addedStatLines.push({
          source: `The Light of Meaning (${nodeId}): ${jewel.name}`,
          lines,
        });
      }
      details.push({
        nodeId,
        jewelName: jewel.name,
        kind: 'light-of-meaning',
        radiusLabel,
        radiusPx,
        nodesInRadius: nonJewelPassives.length,
        notablesInRadius: notables.length,
        smallsInRadius: smalls.length,
      });
    }

    // --- D. PoE 1 Might of the Meek ---
    if (nonKeystoneEffectPct > 0 || disablesNotables) {
      if (disablesNotables) {
        for (const n of notables) {
          suppressedNodeIds.add(n.id);
        }
      }
      if (nonKeystoneEffectPct > 0) {
        const mult = 1 + nonKeystoneEffectPct / 100;
        const lines: string[] = [];
        // Non-keystone passives whose stats are not disabled (smalls; plus notables only if not disabled)
        const affected = disablesNotables ? smalls : [...smalls, ...notables];
        for (const n of affected) {
          for (const st of n.stats) {
            const delta = scaleStatLineDelta(st, mult);
            if (delta) lines.push(delta);
          }
        }
        if (lines.length > 0) {
          addedStatLines.push({
            source: `Might of the Meek (${nodeId}): ${jewel.name}`,
            lines,
          });
        }
      }
      details.push({
        nodeId,
        jewelName: jewel.name,
        kind: 'might-of-the-meek',
        radiusLabel,
        radiusPx,
        nodesInRadius: inRadius.length,
        notablesInRadius: notables.length,
        smallsInRadius: smalls.length,
      });
    }

    // --- D2. PoE 1 Unnatural Instinct & Elegant Hubris (Small passive suppression / unallocated grants) ---
    if (disablesAllocatedSmalls || eternalHubrisConquered) {
      const effRadius: JewelRadiusLabel = eternalHubrisConquered ? 'Large' : radiusLabel;
      const effPx = getJewelRadiusPx(effRadius, tree.game, tree.version);
      const effAllocated = getAllocatedNodesInRadius(socketNode, tree, activeTreeNodes, effPx);
      for (const n of effAllocated) {
        if (n.kind === 'small' && !n.ascendancyId) {
          suppressedNodeIds.add(n.id);
        }
      }
    }
    if (grantsUnallocatedSmalls) {
      const rSq = radiusPx * radiusPx;
      const unallocLines: string[] = [];
      for (const n of Object.values(tree.nodes)) {
        if (n.id === socketNode.id || activeTreeNodes.has(n.id)) continue;
        if (n.kind !== 'small' || n.ascendancyId) continue;
        const dx = n.x - socketNode.x;
        const dy = n.y - socketNode.y;
        if (dx * dx + dy * dy <= rSq) {
          unallocLines.push(...n.stats);
        }
      }
      if (unallocLines.length > 0) {
        addedStatLines.push({
          source: `Unnatural Instinct (${nodeId}): ${jewel.name}`,
          lines: unallocLines,
        });
      }
    }

    // --- E. PoE 1 Attribute Conversion Jewels (Fluid Motion, Brute Force Solution, etc.) ---
    if (attrConversions.length > 0) {
      for (const { from, to } of attrConversions) {
        let totalFrom = 0;
        for (const n of nonJewelPassives) {
          const mods = parseModLines(n.stats, `Tree: ${n.name.en}`);
          for (const mod of mods) {
            if (
              mod.name === from &&
              mod.type === 'BASE' &&
              typeof mod.value === 'number'
            ) {
              totalFrom += mod.value;
            }
          }
        }
        if (totalFrom > 0) {
          const src = `Jewel Conversion (${nodeId}): ${jewel.name}`;
          addedMods.push(
            {
              name: from,
              type: 'BASE',
              value: -totalFrom,
              flags: 0,
              keywordFlags: 0,
              source: src,
            },
            {
              name: to,
              type: 'BASE',
              value: totalFrom,
              flags: 0,
              keywordFlags: 0,
              source: src,
            },
          );
        }
      }
      details.push({
        nodeId,
        jewelName: jewel.name,
        kind: 'attr-conversion',
        radiusLabel,
        radiusPx,
        nodesInRadius: nonJewelPassives.length,
      });
    }
  }

  return {
    addedStatLines,
    addedMods,
    suppressedNodeIds,
    details,
  };
}

// ---------------------------------------------------------------------------
// 5. Cluster Jewel Allocation Fix (Prevents Over-Allocating Unallocated Smalls)
// ---------------------------------------------------------------------------

/**
 * Parses a PoE 1 Cluster Jewel and computes the actual allocated small passive count
 * when raw XML cluster node IDs (`>= 65536`) are present, preventing over-granting
 * unallocated small cluster nodes.
 */
export function applyClusterJewelAllocationFix(
  jewel: Item,
  rawAllocatedIds: ReadonlyArray<number> | ReadonlySet<number>,
  options?: ClusterJewelAllocationOptions,
): ClusterJewelAllocationResult {
  const allLines = [...jewel.implicits, ...jewel.explicits]
    .map(stripPobTags)
    .filter(Boolean);

  let totalAdded = 0;
  let socketCount = 0;
  let smallEffectPct = 0;
  const notableNames: string[] = [];
  const smallGrants: string[] = [];

  for (const line of allLines) {
    let m = line.match(/^Adds (\d+) Passive Skills$/i);
    if (m) {
      totalAdded = Number(m[1]);
      continue;
    }
    m = line.match(/^(\d+) Added Passive Skills? (?:is|are) (?:a )?Jewel Sockets?$/i);
    if (m) {
      socketCount = Number(m[1]);
      continue;
    }
    m = line.match(/^1 Added Passive Skill is (.+)$/i);
    if (m) {
      notableNames.push(m[1]!.trim());
      continue;
    }
    m = line.match(/^Added Small Passive Skills (?:also )?grant:\s*(.+)$/i);
    if (m) {
      smallGrants.push(m[1]!.trim());
      continue;
    }
    m = line.match(/^Added Small Passive Skills have (\d+)% increased effect$/i);
    if (m) {
      smallEffectPct += Number(m[1]);
      continue;
    }
  }

  const maxSmallCount = Math.max(0, totalAdded - socketCount - notableNames.length);
  const scaledSmallGrants =
    smallEffectPct > 0
      ? smallGrants.map((g) => scaleStatLineNumeric(g, 1 + smallEffectPct / 100))
      : [...smallGrants];

  // Collect raw cluster node IDs (>= 65536) from XML <Spec nodes="...">
  let rawClusterCount = 0;
  for (const id of rawAllocatedIds) {
    if (id >= 65536) rawClusterCount++;
  }

  let allocatedSmallCount = maxSmallCount;
  let usedRawClusterIds = false;

  if (options?.allocatedClusterNodeCount !== undefined) {
    usedRawClusterIds = true;
    const allocatedForJewel = Math.max(0, Math.min(totalAdded, options.allocatedClusterNodeCount));
    allocatedSmallCount = Math.max(
      0,
      Math.min(maxSmallCount, allocatedForJewel - notableNames.length - socketCount),
    );
  } else if (rawClusterCount > 0) {
    usedRawClusterIds = true;
    const divisor =
      options?.totalClusterJewels && options.totalClusterJewels > 1
        ? options.totalClusterJewels
        : 1;
    const allocatedForJewel = Math.min(
      totalAdded,
      Math.round(rawClusterCount / divisor),
    );
    allocatedSmallCount = Math.max(
      0,
      Math.min(maxSmallCount, allocatedForJewel - notableNames.length - socketCount),
    );
  }

  return {
    totalAdded,
    socketCount,
    notableNames,
    smallGrants,
    smallEffectPct,
    scaledSmallGrants,
    maxSmallCount,
    allocatedSmallCount,
    usedRawClusterIds,
  };
}
