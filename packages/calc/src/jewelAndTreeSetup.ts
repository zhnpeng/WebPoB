/**
 * Resolves all active socketed passive-tree jewels without silently dropping:
 * - PoE 2 `Voices` Sinister sockets (`nodeId` not in `activeTreeNodes`)
 * - PoE 1 cluster jewel sub-sockets (`nodeId >= 65536`)
 * - Historical-tree jewel sockets (e.g. 3.29 socket IDs absent from 3.30 `tree.nodes`)
 *
 * Still excludes sockets that belong exclusively to the INACTIVE PoE 2 Weapon Set.
 */
/**
 * Tracks PoE 2 `Voices` Sinister Jewel socket items resolved by `resolveActiveSocketedJewels`.
 * Per official PoB 2 `Modules/CalcSetup.lua:120-126` (`getCorruptedJewelEffect`), `The Adorned`
 * does NOT scale Corrupted Jewels socketed into Sinister Jewel sockets.
 */
const poe2SinisterSocketJewels = new WeakSet<Item>();

export function resolveActiveSocketedJewels(
  build: Build,
  _tree: PassiveTreeData,
  activeTreeNodes: Set<number>,
): ActiveSocketedJewel[] {
  const socketed = build.tree.socketedJewels;
  if (!socketed) return [];

  const inactiveWeaponSetNodes = new Set<number>();
  if (build.game === 'poe2') {
    const inactiveList =
      build.activeWeaponSet === 2
        ? build.tree.weaponSet1NodeIds
        : build.tree.weaponSet2NodeIds;
    for (const id of inactiveList ?? []) {
      inactiveWeaponSetNodes.add(id);
    }
  }

  const isFullTree = Object.keys(_tree.nodes).length > 50;
  const results: ActiveSocketedJewel[] = [];
  for (const [nodeIdStr, itemId] of Object.entries(socketed)) {
    const nodeId = Number(nodeIdStr);
    if (!Number.isFinite(nodeId)) continue;
    const jewel = build.items[itemId];
    if (!jewel) continue;

    // Exclude sockets explicitly belonging only to the inactive PoE 2 weapon set
    if (
      build.game === 'poe2' &&
      inactiveWeaponSetNodes.has(nodeId) &&
      !activeTreeNodes.has(nodeId)
    ) {
      continue;
    }

    // If this socket exists directly on the passive tree, it MUST be allocated to be active
    if (_tree.nodes[nodeId] && !activeTreeNodes.has(nodeId)) {
      continue;
    }

    // In PoE 1 full passive trees, filter out unallocated / orphaned nested expansion sockets and stale socket IDs
    if (build.game === 'poe1' && isFullTree && !_tree.nodes[nodeId] && nodeId < 65536) {
      const expInfo = POE1_EXPANSION_SOCKETS[nodeId];
      if (!expInfo) {
        continue;
      }
      // Walk up to outer Large socket and verify it is allocated on the tree
      let outerSocketId = nodeId;
      let curExp: (typeof POE1_EXPANSION_SOCKETS)[number] | undefined = expInfo;
      while (curExp?.parentSocketId !== undefined) {
        outerSocketId = curExp.parentSocketId;
        curExp = POE1_EXPANSION_SOCKETS[outerSocketId];
      }
      if (_tree.nodes[outerSocketId] && !activeTreeNodes.has(outerSocketId)) {
        continue;
      }
      // Nested Medium/Small expansion sockets only exist when their parent Cluster Jewel is actually socketed (and large enough to have sub-sockets)
      if (expInfo.parentSocketId !== undefined) {
        const directParentId = socketed[expInfo.parentSocketId];
        const directParentItem = directParentId ? build.items[directParentId] : undefined;
        let hasParentCluster = Boolean(
          directParentItem &&
            isClusterJewelItem(directParentItem) &&
            !(expInfo.socketSize === 0 && /small cluster/i.test(directParentItem.baseName)),
        );
        if (!hasParentCluster && expInfo.socketSize === 0 && expInfo.mediumSocketIndex === 0 && !directParentItem) {
          const outerItemId = socketed[outerSocketId];
          const outerItem = outerItemId ? build.items[outerItemId] : undefined;
          hasParentCluster = Boolean(outerItem && isClusterJewelItem(outerItem));
        }
        if (!hasParentCluster) {
          continue;
        }
      }
    }

    const isVoicesOrVirtual = !activeTreeNodes.has(nodeId);
    results.push({ nodeId, jewel, isVoicesOrVirtual });
  }

  // Mark PoE 2 virtual Sinister Jewel sockets added by `Voices` so `computeJewelEffectScale`
  // excludes them from `The Adorned` scaling (`CalcSetup.lua:120-126`).
  if (build.game === 'poe2') {
    const hasVoicesSinister = results.some(({ jewel }) =>
      [...jewel.implicits, ...jewel.explicits].some((l) =>
        /^Allocates\s+\d+\s+Sinister\s+Jewel\s+sockets?$/i.test(stripPobTags(l)),
      ),
    );
    if (hasVoicesSinister) {
      for (const entry of results) {
        if (!_tree.nodes[entry.nodeId]) {
          poe2SinisterSocketJewels.add(entry.jewel);
        }
      }
    }
  }

  return results;
}

