/**
 * Strips PoB metadata tags like `{enchant}`, `{crafted}`, `{fractured}`, `{variant:1,2}`, `{range:0.5}`
 * and normalizes whitespace.
 */
function stripPobTags(line: string): string {
  return normalizeStatLineToEn(
    line.replace(/\{[^}]+\}/g, '').trim(),
  ).trim();
}

function isItemCorrupted(item: Item): boolean {
  if (item.corrupted) return true;
  if (item.rawText && /^\s*(?:Twice\s+)?Corrupted\s*$/im.test(item.rawText)) {
    return true;
  }
  return false;
}

function getActiveEquippedItemsForAnoints(build: Build): Item[] {
  const items: Item[] = [];
  const hasSwap = Boolean(
    build.equipped['Weapon 1 Swap'] || build.equipped['Weapon 2 Swap'],
  );

  for (const [slot, itemId] of Object.entries(build.equipped)) {
    if (!itemId) continue;
    if (build.game === 'poe2') {
      if (
        build.activeWeaponSet === 1 &&
        (slot === 'Weapon 1 Swap' || slot === 'Weapon 2 Swap')
      ) {
        continue;
      }
      if (
        build.activeWeaponSet === 2 &&
        hasSwap &&
        (slot === 'Weapon 1' || slot === 'Weapon 2')
      ) {
        continue;
      }
    }
    const item = build.items[itemId];
    if (item) items.push(item);
  }
  return items;
}

/**
 * Official PoB pixel radii for jewel radius evaluation.
 * - PoE 1 (3.16+ including 3.30): Small 960, Medium 1440, Large 1800, Very Large 2400, Massive 2880.
 *   (Pre-3.16 trees <= 3.15: Small 800, Medium 1200, Large 1500, Very Large 1800).
 * - PoE 2 (0.1 / 0.5): Base (1000 / 1150 / 1300 / 1500) × PassiveTreeJewelDistanceMultiplier (1.2)
 *   = Small 1200, Medium 1380, Large 1560, Very Large 1800.
 */
export function getJewelRadiusPx(
  label: JewelRadiusLabel,
  game: GameId,
  treeVersion?: string,
): number {
  if (game === 'poe2') {
    switch (label) {
      case 'Small':
        return 1200; // 1000 * 1.2
      case 'Medium':
        return 1380; // 1150 * 1.2
      case 'Large':
        return 1560; // 1300 * 1.2
      case 'Very Large':
      case 'Massive':
        return 1800; // 1500 * 1.2
    }
  }

  // PoE 1: check if legacy <= 3.15 tree
  if (treeVersion) {
    const m = treeVersion.match(/^(\d+)_(\d+)/);
    if (m) {
      const major = Number(m[1]);
      const minor = Number(m[2]);
      if (major < 3 || (major === 3 && minor <= 15)) {
        switch (label) {
          case 'Small':
            return 800;
          case 'Medium':
            return 1200;
          case 'Large':
            return 1500;
          case 'Very Large':
          case 'Massive':
            return 1800;
        }
      }
    }
  }

  // PoE 1 3.16+ (including 3.29 / 3.30)
  switch (label) {
    case 'Small':
      return 960;
    case 'Medium':
      return 1440;
    case 'Large':
      return 1800;
    case 'Very Large':
      return 2400;
    case 'Massive':
      return 2880;
  }
}

function resolveJewelRadiusLabel(jewel: Item, game: GameId): JewelRadiusLabel {
  const allLines = [...jewel.implicits, ...jewel.explicits].map(stripPobTags);

  // 1. Explicit upgrade mod on PoE 2 Time-Lost jewels: "Upgrades Radius to Very Large"
  for (const line of allLines) {
    const m = line.match(
      /^Upgrades Radius to (Small|Medium|Large|Very Large|Massive)$/i,
    );
    if (m) {
      return normalizeRadiusLabel(m[1]!);
    }
  }

  // 2. Explicit "Radius: <Label>" header in rawText
  if (jewel.rawText) {
    const m = jewel.rawText.match(
      /^\s*Radius\s*:\s*(Small|Medium|Large|Very Large|Massive)\b/im,
    );
    if (m) {
      return normalizeRadiusLabel(m[1]!);
    }
  }

  // 3. Sensible defaults by jewel type
  const lowerName = jewel.name.toLowerCase();
  const lowerBase = jewel.baseName.toLowerCase();
  if (lowerName === 'against the darkness') {
    return 'Large';
  }
  if (lowerBase.includes('time-lost')) {
    return game === 'poe2' ? 'Medium' : 'Large';
  }
  if (
    lowerName === 'the light of meaning' ||
    lowerName === 'might of the meek' ||
    lowerName === 'fluid motion' ||
    lowerName === 'brute force solution' ||
    lowerName === 'careful planning' ||
    lowerName === 'fertile mind' ||
    lowerName === 'inertia'
  ) {
    return 'Large';
  }

  return 'Medium';
}

function normalizeRadiusLabel(raw: string): JewelRadiusLabel {
  const lower = raw.trim().toLowerCase();
  if (lower === 'small') return 'Small';
  if (lower === 'medium') return 'Medium';
  if (lower === 'large') return 'Large';
  if (lower === 'very large') return 'Very Large';
  if (lower === 'massive') return 'Massive';
  return 'Medium';
}

