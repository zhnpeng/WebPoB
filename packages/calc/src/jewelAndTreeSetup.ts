/**
 * Collects all passive notable nodes granted by:
 * - Equipped items (Amulets, Raven-Touched Helmets, Stranglegasp, Sporeguard, Stampede, etc.)
 * - Socketed jewels (Megalomaniac — up to 3 notables!)
 * - Matching `Forbidden Flame` + `Forbidden Flesh` pairs (grants the ascendancy notable once)
 *
 * Ignores non-notable allocation lines (e.g. `Allocates 2 Sinister Jewel sockets` on Voices)
 * and deduplicates against `activeTreeNodes` and across multiple anoint sources.
 */
export function collectAllocatedAnointNodes(
  build: Build,
  tree: PassiveTreeData,
  activeTreeNodes: Set<number>,
): PassiveNode[] {
  // Build case-insensitive name lookup over tree nodes
  const notableByName = new Map<string, PassiveNode>();
  const ascendancyNotableByName = new Map<string, PassiveNode>();
  const fallbackByName = new Map<string, PassiveNode>();

  for (const node of Object.values(tree.nodes)) {
    const key = node.name.en.trim().toLowerCase();
    if (!key) continue;
    if (node.kind === 'notable') {
      if (node.ascendancyId) {
        if (!ascendancyNotableByName.has(key)) {
          ascendancyNotableByName.set(key, node);
        }
      } else if (!notableByName.has(key)) {
        notableByName.set(key, node);
      }
    } else if (!fallbackByName.has(key)) {
      fallbackByName.set(key, node);
    }
  }

  const lookupNode = (name: string, preferAscendancy: boolean): PassiveNode | undefined => {
    const key = name.trim().toLowerCase();
    if (!key) return undefined;
    if (preferAscendancy) {
      return (
        ascendancyNotableByName.get(key) ??
        notableByName.get(key) ??
        fallbackByName.get(key)
      );
    }
    return (
      notableByName.get(key) ??
      ascendancyNotableByName.get(key) ??
      fallbackByName.get(key)
    );
  };

  const grantedNodeIds = new Set<number>();
  const result: PassiveNode[] = [];

  const grantNotable = (name: string, preferAscendancy: boolean) => {
    const node = lookupNode(name, preferAscendancy);
    if (!node) return;
    if (activeTreeNodes.has(node.id)) return;
    if (grantedNodeIds.has(node.id)) return;
    grantedNodeIds.add(node.id);
    result.push(node);
  };

  // Track Forbidden Flame & Forbidden Flesh candidates separately
  const flameNotables = new Set<string>();
  const fleshNotables = new Set<string>();

  const scanItemLines = (item: Item) => {
    const allLines = [...item.implicits, ...item.explicits];
    for (const rawLine of allLines) {
      const line = stripPobTags(rawLine);
      if (!line) continue;

      // Ignore Voices / jewel socket allocation lines: "Allocates 2 Sinister Jewel sockets"
      if (/^Allocates\s+\d+\s+.*jewel\s+sockets?$/i.test(line)) {
        continue;
      }

      // Forbidden Flame / Forbidden Flesh pair check
      const mForbidden = line.match(
        /^Allocates\s+(.+?)\s+if you have the matching modifier on Forbidden\s+(Flame|Flesh)$/i,
      );
      if (mForbidden) {
        const notableName = mForbidden[1]!.trim();
        const partner = mForbidden[2]!.toLowerCase();
        // If line says "...on Forbidden Flesh", this item is Forbidden Flame; and vice versa.
        if (partner === 'flesh') {
          flameNotables.add(notableName.toLowerCase());
        } else {
          fleshNotables.add(notableName.toLowerCase());
        }
        continue;
      }

      // Standard anoint / Megalomaniac line: "Allocates <NotableName>"
      const mAlloc = line.match(/^Allocates\s+(.+)$/i);
      if (mAlloc) {
        const notableName = mAlloc[1]!.trim();
        if (notableName) {
          grantNotable(notableName, false);
        }
      }
    }
  };

  // Scan all active equipped items
  for (const item of getActiveEquippedItemsForAnoints(build)) {
    scanItemLines(item);
  }

  // Scan all active socketed jewels (including Voices / virtual sockets)
  const activeJewels = resolveActiveSocketedJewels(build, tree, activeTreeNodes);
  for (const { jewel } of activeJewels) {
    scanItemLines(jewel);
  }

  // Grant any matched Forbidden Flame + Forbidden Flesh ascendancy notables once
  for (const notableKey of flameNotables) {
    if (fleshNotables.has(notableKey)) {
      grantNotable(notableKey, true);
    }
  }

  return result;
}

